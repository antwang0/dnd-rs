/// Magic Missile — the classic auto-hit force-damage cantrip-in-spirit
/// (actually level 1 in 5e). Three darts, each 1d4+1 force. No attack
/// roll, no save. Modeled here with a single target for simplicity (5e
/// allows split targets but that's a targeting-schema question we don't
/// have infrastructure for yet).
pub struct MagicMissile {}

impl Action for MagicMissile {
    fn name(&self) -> &str {
        "magic missile"
    }

    fn aliases(&self) -> Vec<&str> {
        vec!["mm", "missile"]
    }

    fn targeting_schema(&self) -> TargetingSchema {
        TargetingSchema::SingleActor
    }

    fn reach_tiles(&self) -> Option<isize> {
        // 120 ft
        Some(48)
    }

    fn requires_los(&self) -> bool {
        true
    }

    fn damage_types(&self) -> &'static [DamageType] {
        &[DamageType::Force]
    }

    fn cost(
        &self,
        _encounter: &EncounterInstance,
        _caster_id: usize,
        _target_ids: Option<&Vec<usize>>,
        _target_locations: Option<&Vec<Coordinate>>,
        _overrides: Option<&HashSet<ActionOverride>>,
    ) -> Vec<Resource> {
        vec![Resource::Action, Resource::SpellSlot(1)]
    }

    fn side_effects(
        &self,
        encounter: &mut EncounterInstance,
        _caster_id: usize,
        target_ids: Option<&Vec<usize>>,
        _target_locations: Option<&Vec<Coordinate>>,
        _overrides: Option<&HashSet<ActionOverride>>,
    ) -> Vec<Box<dyn ApplicableSideEffect>> {
        let Some(target_id) = target_ids.and_then(|ids| ids.first().copied()) else {
            return Vec::new();
        };
        // 3 darts × (1d4+1) each. Auto-hits; damage rolls separately per
        // dart per 5e RAW.
        let mut total = 0u32;
        let mut breakdown = Vec::with_capacity(3);
        for _ in 0..3 {
            let r = encounter.roll(&Dice::new(1, 4));
            let dart = r + 1;
            breakdown.push(format!("{}(1d4+1)", dart));
            total += dart;
        }
        encounter.log(format!(
            "  magic missile: {} = {} force (auto-hit)",
            breakdown.join("+"),
            total
        ));
        vec![Box::new(DealDamage {
            actor_id: target_id,
            amount: total,
            damage_type: DamageType::Force,
        })]
    }
}

