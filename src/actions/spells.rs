/// Bless — concentration buff spell. Up to 3 allies (self-targeted for
/// simplicity here: applies to caster + 2 nearest allies within 6 tiles /
/// 30ft). Recipients get the `Helped` condition for its 1-round advantage
/// (approximation of the +1d4 to attack/save that Bless grants in RAW).
/// Concentration spell; overwrites any prior concentration.
pub struct Bless {}

impl Action for Bless {
    fn name(&self) -> &str {
        "bless"
    }

    fn aliases(&self) -> Vec<&str> {
        vec!["bl"]
    }

    fn targeting_schema(&self) -> TargetingSchema {
        TargetingSchema::NoArgs
    }

    fn is_harmful(&self) -> bool {
        false
    }

    fn cost(
        &self,
        _encounter: &EncounterInstance,
        _caster_id: usize,
        _target_ids: Option<&Vec<usize>>,
        _target_locations: Option<&Vec<Coordinate>>,
        _overrides: Option<&HashSet<ActionOverride>>,
    ) -> Vec<Resource> {
        vec![Resource::Action, Resource::SpellSlot(1)]
    }

    fn side_effects(
        &self,
        encounter: &mut EncounterInstance,
        caster_id: usize,
        _target_ids: Option<&Vec<usize>>,
        _target_locations: Option<&Vec<Coordinate>>,
        _overrides: Option<&HashSet<ActionOverride>>,
    ) -> Vec<Box<dyn ApplicableSideEffect>> {
        use crate::actors::actor_template::ConcentrationData;
        use crate::conditions::{Condition, ConditionTimer};
        use crate::engine::side_effects::{ApplyCondition, StartConcentration};
        use crate::engine::util::{footprint_chebyshev, get_tiles_from_size};

        let Some(caster) = encounter.actors.get(&caster_id) else {
            return Vec::new();
        };
        let team = caster.team();
        let loc = caster.location();
        let size = get_tiles_from_size(caster.size());

        // Find up to 3 team-mates (including self) inside 6-tile Bless
        // range, deterministic by (distance, id) so seed-reproducible.
        let mut ranked: Vec<(isize, usize)> = encounter
            .actors
            .iter()
            .filter_map(|(id, a)| {
                if a.team() != team || !a.is_combat_active() {
                    return None;
                }
                let d = footprint_chebyshev(loc, size, a.location(), get_tiles_from_size(a.size()));
                if d > 12 { None } else { Some((d, *id)) }
            })
            .collect();
        ranked.sort_by_key(|(d, id)| (*d, *id));
        let picks: Vec<usize> = ranked.into_iter().take(3).map(|(_, id)| id).collect();
        if picks.is_empty() {
            return Vec::new();
        }

        let mut effects: Vec<Box<dyn ApplicableSideEffect>> = Vec::new();
        let mut conditions_for_concentration = Vec::new();
        for id in &picks {
            effects.push(Box::new(ApplyCondition {
                actor_id: *id,
                condition: Condition::Helped,
                timer: ConditionTimer::Rounds(10),
            }));
            conditions_for_concentration.push((*id, Condition::Helped));
        }
        // The concentration handle so drop_concentration cleans everyone up.
        effects.push(Box::new(StartConcentration {
            caster_id,
            data: ConcentrationData {
                spell_name: "Bless".to_string(),
                conditions: conditions_for_concentration,
            },
        }));
        effects
    }
}

