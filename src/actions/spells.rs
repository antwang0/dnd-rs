/// Guiding Bolt — level-1 leveled spell. Spell attack roll (ranged): on hit
/// 4d6 radiant AND the target grants advantage to the next attack roll
/// against them (via the `Helped` marker … re-used since it means "the next
/// attack against the target has advantage" too — we express that on the
/// *attacker* side with the same buff mechanism, applied to the target's
/// team-mates by not applying it here). Instead we take the simple route:
/// apply the `Blinded` condition for 1 round with a WIS DC save, since
/// "glowing target" isn't a modeled condition — bookmark this once
/// per-target advantage is a first-class primitive.
pub struct GuidingBolt {}

impl Action for GuidingBolt {
    fn name(&self) -> &str {
        "guiding bolt"
    }

    fn aliases(&self) -> Vec<&str> {
        vec!["gb", "bolt"]
    }

    fn targeting_schema(&self) -> TargetingSchema {
        TargetingSchema::SingleActor
    }

    fn reach_tiles(&self) -> Option<isize> {
        // 120 ft = 48 tiles. Effectively unlimited on current maps.
        Some(48)
    }

    fn requires_los(&self) -> bool {
        true
    }

    fn damage_types(&self) -> &'static [DamageType] {
        &[DamageType::Radiant]
    }

    fn cost(
        &self,
        _encounter: &EncounterInstance,
        _caster_id: usize,
        _target_ids: Option<&Vec<usize>>,
        _target_locations: Option<&Vec<Coordinate>>,
        _overrides: Option<&HashSet<ActionOverride>>,
    ) -> Vec<Resource> {
        vec![Resource::Action, Resource::SpellSlot(1)]
    }

    fn side_effects(
        &self,
        encounter: &mut EncounterInstance,
        caster_id: usize,
        target_ids: Option<&Vec<usize>>,
        _target_locations: Option<&Vec<Coordinate>>,
        _overrides: Option<&HashSet<ActionOverride>>,
    ) -> Vec<Box<dyn ApplicableSideEffect>> {
        let Some(target_id) = target_ids.and_then(|ids| ids.first().copied()) else {
            return Vec::new();
        };
        let Some(caster) = encounter.actors.get(&caster_id) else {
            return Vec::new();
        };
        // Spell attack bonus: use WIS mod (proficiency not modeled).
        let wis_mod = modifier_from_score(caster.ability_score(AbilityScoreType::Wisdom));
        let target_ac = encounter.actors.get(&target_id).map(|a| a.armor_class() as i32);
        let Some(target_ac) = target_ac else {
            return Vec::new();
        };
        let mode = encounter.compute_attack_mode(caster_id, target_id, false);
        let raw_d20 = encounter.roll_d20_with_mode(mode) as i32;
        let total = raw_d20 + wis_mod;
        let hit = raw_d20 == 20 || total >= target_ac;
        encounter.log(format!(
            "  guiding bolt: 1d20({}){:+} = {} vs AC {}{} \u{2014} {}",
            raw_d20,
            wis_mod,
            total,
            target_ac,
            mode.log_suffix(),
            if hit { "hit" } else { "miss" }
        ));
        if !hit {
            return Vec::new();
        }
        let raw = encounter.roll(&Dice::new(4, 6));
        encounter.log(format!("  guiding bolt: 4d6({}) = {} radiant", raw, raw));
        vec![Box::new(DealDamage {
            actor_id: target_id,
            amount: raw,
            damage_type: DamageType::Radiant,
        })]
    }
}

