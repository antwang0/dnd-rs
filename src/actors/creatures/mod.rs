    #[test]
    fn the_bestiary_agrees_with_the_srd_about_what_hurts() {
        let mut wrong: Vec<String> = Vec::new();
        for (t, rows) in damage_row_table() {
            for &(damage_type, expected) in rows {
                let actual = t.damage_modifiers.get(&damage_type).copied();
                if actual != expected {
                    wrong.push(format!(
                        "{}: SRD says {} is {:?}, template says {:?}",
                        t.name, damage_type, expected, actual
                    ));
                }
            }
        }
        assert!(
            wrong.is_empty(),
            "damage rows disagree with SRD 5.2:\n  {}",
            wrong.join("\n  ")
        );
    }

    #[test]
    fn the_bestiary_agrees_with_the_srd_about_who_gets_tired() {
        let wrong: Vec<String> = exhaustion_immunity_table()
            .into_iter()
            .filter_map(|(t, expected)| {
                let actual = t.condition_immunities.contains(&Condition::Exhausted);
                (actual != expected).then(|| {
                    format!(
                        "{}: SRD says immune={}, template says {}",
                        t.name, expected, actual
                    )
                })
            })
            .collect();
        assert!(
            wrong.is_empty(),
            "exhaustion immunity disagrees with SRD 5.2:\n  {}",
            wrong.join("\n  ")
        );
    }

    /// The four skills the engine actually rolls, and the templates that
    /// have to claim them for the lanes reading each one to have any
    /// content behind it.
    ///
    /// This is a data-coverage sweep rather than a behavior test, and it
    /// exists because the failure it guards against is silent. Every one
    /// of these skills feeds a rule — Perception the passive score and
    /// the Search action, Stealth the Hide action and the DC Search
    /// compares against, Athletics and Acrobatics both halves of every
    /// shove, grapple, and escape. A skill nothing claims makes its rule
    /// a coin flip that nobody is ever better at, which reads exactly
    /// like the rule working.
    const ENGINE_READ_SKILLS: &[Skill] = &[
        Skill::Perception,
        Skill::Stealth,
        Skill::Athletics,
        Skill::Acrobatics,
    ];

    #[test]
    fn every_skill_the_engine_rolls_is_claimed_by_some_template() {
        let families = super::pc_template_families();
        for skill in ENGINE_READ_SKILLS {
            let claimed = families
                .iter()
                .flat_map(|(_, templates)| templates.iter())
                .any(|t| t.skills.contains(skill));
            assert!(
                claimed,
                "{:?} is read by the engine but no player template is proficient in it",
                skill
            );
        }
    }

    /// A subclass template clones its family's base wholesale, so the
    /// skill picks land on every build in the family rather than only on
    /// the bare chassis. Pinned because the propagation is implicit —
    /// it rides `..BASE.clone()` in each subclass literal, and a
    /// subclass that spelled its fields out by hand would quietly drop
    /// them.
    #[test]
    fn subclass_templates_inherit_their_familys_skills() {
        for (family, templates) in super::pc_template_families() {
            let Some(base) = templates.first() else {
                continue;
            };
            if base.skills.is_empty() {
                continue;
            }
            for template in &templates[1..] {
                for skill in &base.skills {
                    assert!(
                        template.skills.contains(skill),
                        "{} ({}) dropped {:?} from the family baseline",
                        template.name,
                        family,
                        skill
                    );
                }
            }
        }
    }

    /// `aquatic_templates` is the whole truth about who carries
    /// `SWIM_SPEED_TAG`: every entry does, and no template anywhere else
    /// in the engine does.
    ///
    /// Deliberately narrower than "who swims". Two player builds have a
    /// swimming speed without this tag — the Scout Rogue's Superior
    /// Mobility and the Ranger's Roving both grant one as a clause of a
    /// class feature, and both reach `has_swim_speed` through their own
    /// row on `SWIM_SPEED_SOURCES`. The tag is the *monster stat block*
    /// lane specifically, and the list is the roster of stat blocks that
    /// have a swim line.
    ///
    /// The second half is a genuine invariant rather than a restatement
    /// of the list. The tag is one short line inside a struct literal
    /// that also holds Blood Frenzy, Pack Tactics and a dozen other
    /// one-line tags, and the failure mode it guards is silent in both
    /// directions: a swimmer that loses the tag pays double to cross a
    /// pool it lives in, and a lander that gains one wades through a
    /// lake and stabs out of it at no penalty. Neither shows up as a
    /// crash, a warning, or a visibly wrong number — only as a fight
    /// that plays slightly wrong.
    ///
    /// Swept across the whole engine's reach — the encounter template
    /// pool plus every player template — rather than across the aquatic
    /// list alone, because a list can only catch what is on it and the
    /// interesting failure is a tag that ended up somewhere the list
    /// never looks.
    #[test]
    fn the_swim_speed_tag_is_carried_by_exactly_the_aquatic_templates() {
        use crate::actions::class_features::SWIM_SPEED_TAG;
        use crate::engine::encounter::EncounterInstance;

        let aquatic = super::aquatic_templates();
        for t in &aquatic {
            assert!(
                t.features.contains(SWIM_SPEED_TAG),
                "{} is on the aquatic list without a swimming speed",
                t.name
            );
        }
        let aquatic_names: Vec<&str> = aquatic.iter().map(|t| t.name).collect();

        let everything = EncounterInstance::template_pool().into_iter().chain(
            super::pc_template_families()
                .into_iter()
                .flat_map(|(_, ts)| ts),
        );
        for t in everything {
            if !t.features.contains(SWIM_SPEED_TAG) {
                continue;
            }
            assert!(
                aquatic_names.contains(&t.name),
                "{} carries a swimming speed but is not on the aquatic list",
                t.name
            );
        }
    }

    /// The tag reaches the two predicates that read it, on a real
    /// instance rather than on the template literal.
    ///
    /// Worth its own test because the two answer deliberately different
    /// questions — `has_swim_speed` is RAW's narrow "does this creature
    /// have a swimming speed", `swims_freely` the broader "does the
    /// water charge this creature" — and a refactor that collapsed them
    /// into one would still pass every test above.
    #[test]
    fn an_aquatic_template_instantiates_as_something_that_swims() {
        use crate::actors::actor_template::ActorInstance;
        use crate::engine::dice::FastRandRoller;
        use crate::engine::types::Coordinate;

        for template in super::aquatic_templates() {
            let a = ActorInstance::from_creature_template(
                template,
                Coordinate::new(0, 0),
                0,
                &mut FastRandRoller::with_seed(0),
                0,
            )
            .unwrap();
            assert!(a.has_swim_speed(), "{}", template.name);
            assert!(a.swims_freely(), "{}", template.name);
        }
    }
